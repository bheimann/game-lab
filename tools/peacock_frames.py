"""Builds art-source/peacock/peacock_{down,up,side}.txt. The peacock is the gunner: blue body, crest, a fanned
green tail with eye spots behind it, and a little grey gun held in its wing. Legs are swapped per frame for the walk
(idle, step A, step B). Feet on row 21. Run: python tools/peacock_frames.py, then render with tools/ascii_sprite.py."""
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "art-source" / "peacock"
BLANK16, BLANK20 = "." * 16, "." * 20


def write(name, comment, frames, width):
    for f in frames:
        assert len(f) == 28 and all(len(r) == width for r in f), (name, [(i, len(r)) for i, r in enumerate(f) if len(r) != width])
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text(comment + "\n" + "\n\n".join("\n".join(f) for f in frames) + "\n", encoding="utf-8")


def overlay(base, piece, top, left):
    """Paints piece onto base (both lists of strings); '.' in piece is see-through."""
    rows = [list(r) for r in base]
    for dy, line in enumerate(piece):
        for dx, ch in enumerate(line):
            if ch != ".":
                rows[top + dy][left + dx] = ch
    return ["".join(r) for r in rows]


