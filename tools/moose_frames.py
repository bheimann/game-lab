"""Builds art-source/moose/moose_{down,up,side}.txt. The front/back views are drawn as left halves and mirrored;
the legs are swapped per frame for the walk (idle, step A, step B). Feet on row 21, antlers in the top rows.
Run: python tools/moose_frames.py, then render each file with tools/ascii_sprite.py."""
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "art-source" / "moose"
BLANK16, BLANK20 = "." * 16, "." * 20


def mirror(halves):
    return [h + h[::-1] for h in halves]


def write(name, comment, frames, width):
    for f in frames:
        assert len(f) == 28 and all(len(r) == width for r in f), (name, [(i, len(r)) for i, r in enumerate(f) if len(r) != width])
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text(comment + "\n" + "\n\n".join("\n".join(f) for f in frames) + "\n", encoding="utf-8")


ANTLERS = [
    "o.o.o...",
    "oToToo..",
    "oTTTTo..",
    ".otTTTo.",
    "..ootToo",
]

