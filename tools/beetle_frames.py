"""Builds art-source/beetle/giant_beetle.txt: a big top-down scarab beetle facing up (the game rotates it to
the 4 directions). Shapes are computed (ellipses for the shell and head, lines for legs and mandibles) and
then outlined. Frames: walk A, walk B. Run: python tools/beetle_frames.py"""
from pathlib import Path

W, H = 26, 32
OUT = Path(__file__).resolve().parent.parent / "art-source" / "beetle"


def frame(step):
    g = [["." for _ in range(W)] for _ in range(H)]
    cx = (W - 1) / 2

    def put(x, y, c):
        if 0 <= x < W and 0 <= y < H:
            g[y][x] = c

    # Legs first (the shell covers their roots): three pairs, front ones reach forward, back ones backward.
    # On each step the legs on one side move forward a pixel while the other side moves back.
    for y, slant in ((12, -1), (18, 0), (24, 1)):
        for side in (-1, 1):
            shift = (1 if step == 0 else -1) * side * (1 if slant == 0 else slant)
            x = int(cx + side * 6.5 + (0.5 if side > 0 else 0))
            for t in range(4):
                put(x + side * t, y + shift, "n")
            put(x + side * 4, y + shift + (slant or 1), "n")
            put(x + side * 4, y + shift + 2 * (slant or 1), "n")

    # Mandibles / horns curving forward.
    for side in (-1, 1):
        for x, y in ((3, 5), (3, 4), (4, 3), (4, 2), (3, 1)):
            put(int(cx + side * x + (0.5 if side > 0 else -0.5)), y, "g")

    # Head.
    for y in range(H):
        for x in range(W):
            if ((x - cx) / 4.6) ** 2 + ((y - 7.5) / 3.2) ** 2 <= 1:
                put(x, y, "n")
    put(int(cx - 2.5), 7, "R")
    put(int(cx + 3.5), 7, "R")

    # Shell: two wing cases with a seam down the middle, shaded on the left, shine top-left.
    for y in range(H):
        for x in range(W):
            if ((x - cx) / 8.6) ** 2 + ((y - 19) / 10.5) ** 2 <= 1:
                c = "M"
                if x < cx - 5.5:
                    c = "D"
                if ((x - (cx - 4)) / 1.8) ** 2 + ((y - 14) / 2.6) ** 2 <= 1:
                    c = "B"
                if ((x - (cx - 4)) / 0.8) ** 2 + ((y - 13) / 1.2) ** 2 <= 1:
                    c = "L"
                if abs(x - cx) < 1 and y > 10:
                    c = "o"
                put(x, y, c)

    # Outline every empty pixel that touches a filled one.
    filled = {(x, y) for y in range(H) for x in range(W) if g[y][x] != "."}
    for y in range(H):
        for x in range(W):
            if g[y][x] == "." and any((x + dx, y + dy) in filled for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                g[y][x] = "o"
    return ["".join(r) for r in g]


OUT.mkdir(parents=True, exist_ok=True)
frames = [frame(0), frame(1)]
(OUT / "giant_beetle.txt").write_text(
    "# Giant beetle (boss), top-down, facing up. Frames: walk A, walk B. Generated by tools/beetle_frames.py\n"
    + "\n\n".join("\n".join(f) for f in frames) + "\n", encoding="utf-8")
print("\n".join(frames[0]))
