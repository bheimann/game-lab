"""Builds art-source/deer/deer_walk.txt: the deer enemy facing right (the game mirrors it for left).
Frames are 40x42 with the hooves on the bottom row; the body is shared and the four legs swing per frame.
Run: python tools/deer_frames.py, then render with tools/ascii_sprite.py."""
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "art-source" / "deer"
W, H = 40, 42

BODY = [
    "........................................",
    "........................................",
    "........................................",
    "........................................",
    "........................................",
    "........................................",
    "..........................T.......T.....",
    "..........................T..T.T..T.....",
    "...........................TT...TT......",
    "............................T...T.......",
    "............................T...T.......",
    "............................T...T.......",
    "........................ooo.ooooooo.....",
    ".......................oEkEoEEEEEEEo....",
    "........................oEEoEEEPEEEEoo..",
    ".........................ooEEEEEEEEEETo.",
    "..........................oEEEEEEETTTPo.",
    "..........................oEEEEEoooooo..",
    "..........................oEEEEo........",
    ".........................oEEEEEo........",
    ".........................oEEEEEo........",
    "........................oEEEEEEo........",
    "........................oEEEEEEo........",
    "...oo...................oEEEEEEo........",
    "..oWWoooooooooooooooooooEEEEEEEo........",
    "..oWEEEEEEEEEEEEEEEEEEEEEEEEEEEo........",
    "...oEEEEEEEEEEEEEEEEEEEEEEEEEEEo........",
    "...oEEEEEEEEEEEEEEEEEEEEEEEEEEo.........",
    "...oeEEEEEEEEEEEEEEEEEEEEEEEEEo.........",
    "...oeeEEEEEEEEEEEEEEEEEEEEEEEeo.........",
    "....oeeEEETTTTTTTTTTTTTTTEEEeo..........",
    ".....oeeeooooooooooooooooeeeo...........",
]
assert len(BODY) == 32 and all(len(r) == W for r in BODY), [i for i, r in enumerate(BODY) if len(r) != W]

# (x at the hip, colour) for each leg; far legs are drawn first so the near ones overlap them.
LEGS = {"back_far": (9, "e"), "front_far": (27, "e"), "back_near": (6, "E"), "front_near": (24, "E")}
# How far each hoof swings from under its hip, and whether it is lifted, per frame.
SWING = {
    "front_near": [(2, 0), (0, 1), (-2, 0), (0, 0)],
    "back_far": [(2, 0), (0, 1), (-2, 0), (0, 0)],
    "front_far": [(-2, 0), (0, 0), (2, 0), (0, 1)],
    "back_near": [(-2, 0), (0, 0), (2, 0), (0, 1)],
}


def frame(i):
    rows = [list(r) for r in BODY] + [list("." * W) for _ in range(H - len(BODY))]
    for name in ("back_far", "front_far", "back_near", "front_near"):
        x, colour = LEGS[name]
        dx, lift = SWING[name][i]
        bottom = H - 1 - lift
        for y in range(len(BODY), bottom):
            cx = x + round(dx * (y - len(BODY)) / (bottom - len(BODY)))
            rows[y][cx - 1:cx + 2] = ["o", colour, "o"]
        cx = x + dx
        rows[bottom][cx - 1:cx + 2] = ["o", "o", "o"]
    return ["".join(r) for r in rows]


OUT.mkdir(parents=True, exist_ok=True)
(OUT / "deer_walk.txt").write_text(
    "# Deer facing right (mirrored for left). Frames: walk cycle. Hooves on row 41. Generated by tools/deer_frames.py\n"
    + "\n\n".join("\n".join(frame(i)) for i in range(4)) + "\n", encoding="utf-8")
print("ok")
