"""Builds art-source/beetle/beetle_{down,up,side}.txt: the friendly beetle hero (not the giant beetle boss, which
is tools/beetle_frames.py). An upright rhinoceros beetle with a glossy violet shell, one horn and small arms.
Front/back views are drawn as left halves and mirrored; legs are swapped per frame for the walk (idle, step A,
step B). Feet on row 21. Run: python tools/beetle_hero_frames.py, then render with tools/ascii_sprite.py."""
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "art-source" / "beetle"
BLANK16, BLANK20 = "." * 16, "." * 20


def mirror(halves):
    return [h + h[::-1] for h in halves]


def write(name, comment, frames, width):
    for f in frames:
        assert len(f) == 28 and all(len(r) == width for r in f), (name, [(i, len(r)) for i, r in enumerate(f) if len(r) != width])
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text(comment + "\n" + "\n\n".join("\n".join(f) for f in frames) + "\n", encoding="utf-8")


HORN = [
    ".....o..",
    ".....oAo",
    ".....oVV",
    "......oV",
    "......oV",
]
LEGS = {
    "idle": ["....ovvoovvo....", "....ovvoovvo....", "...oooo..oooo..."],
    "a": ["....ovvoovvo....", "....ooooovvo....", "........ooooo..."],
    "b": ["....ovvoovvo....", "....ovvooooo....", "...ooooo........"],
}


def shine(rows, col, top, bottom):
    """The horn and shell are mirrored, so the left-side shine pixel is put back after mirroring."""
    for y in range(top, bottom + 1):
        rows[y] = rows[y][:col] + "A" + rows[y][col + 1:]
    return rows


# ---------- facing down ----------
down_top = shine(mirror(HORN + [
    "....ooVV",
    "...oVVVV",
    "..oVWWVV",
    "..oVWPVV",
    "..ovVVVV",
    "...ovvvP",
    "..oooooo",
    ".oVAVVVV",
    ".ovVVVVV",
    "ovvoAAAA",
    "ovvoVVVV",
    ".oooAAAA",
    "...oVVVV",
    "...ooAAA",
]), 7, 2, 5)
write("beetle_down.txt",
      "# Beetle hero facing down. Frames: idle, left step, right step. Feet on row 21. Generated by tools/beetle_hero_frames.py",
      [down_top + LEGS[k] + [BLANK16] * 6 for k in ("idle", "a", "b")], 16)


def under(leg_row, behind):
    return "".join(c if c != "." else b for c, b in zip(leg_row, behind))


# ---------- facing up ----------
up_top = shine(mirror(HORN + [
    "....ooVV",
    "...oVVVV",
    "...ovVVV",
    "..oooooo",
    ".oVAVVVV",
    ".oVVVVVV",
    ".ovvvvvv",
    "oAAVVVVo",
    "oAVVVVVo",
    "oAVVVVVo",
    "oVVVVVVo",
    "oVVVVVvo",
    ".ovVVvvo",
    "..ovvvvo",
]), 7, 2, 5)
write("beetle_up.txt",
      "# Beetle hero facing up (away). Frames: idle, left step, right step. Feet on row 21. Generated by tools/beetle_hero_frames.py",
      [up_top + [under(LEGS[k][0], "...oooooooooo...")] + LEGS[k][1:] + [BLANK16] * 6 for k in ("idle", "a", "b")], 16)

# ---------- facing right (side) ----------
side_top = [
    "...............oo...",
    "..............oAVo..",
    "..............oVo...",
    ".............oAVo...",
    "............oAVo....",
    "..........ooVVo.....",
    ".........oVVVVVo....",
    ".........oVVWWVo....",
    ".........oVVWPVo....",
    ".........ovVVVvo....",
    "..........ovvvPo....",
    ".......oooooooo.....",
    "......oAAVVoAo......",
    ".....oAVVVVoAAo.....",
    "....oAVVVVVoAvvo....",
    "....oVVVVVVoAovo....",
    "....oVVVVVVoAAo.....",
    "....ovVVVVVoAAo.....",
    ".....ovVVVvoAo......",
]
side_legs = {
    "idle": [".....ooovvovvo......", ".......ovvovvo......", "......oooo.ooooo...."],
    "a": [".....ooovvovvo......", "......ovvo.ovvo.....", ".....oooo...oooo...."],
    "b": [".....ooovvovvo......", "........ovvvo.......", ".......oooooooo....."],
}
write("beetle_side.txt",
      "# Beetle hero facing right (mirrored for left). Frames: idle, stride, legs together. Feet on row 21. Generated by tools/beetle_hero_frames.py",
      [side_top + side_legs[k] + [BLANK20] * 6 for k in ("idle", "a", "b")], 20)
print("ok")
